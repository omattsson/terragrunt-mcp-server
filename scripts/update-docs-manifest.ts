#!/usr/bin/env tsx
/**
 * Docs Manifest Generator
 *
 * Builds `TERRAGRUNT_DOC_MANIFEST` (src/terragrunt/docs-manifest.ts) from the
 * docs tree of an upstream Terragrunt checkout. The manifest lists every page
 * of the upstream `llms-small.txt` with its canonical URL, in the order of the
 * upstream generator (`LLMS_PAGE_SOURCES` in docs/src/lib/generated-pages.ts):
 *
 *   1. the `docs` collection (docs/src/content/docs), sorted by slug,
 *   2. HCL blocks, attributes and functions (docs/src/data/hcl/<kind>), each by name,
 *   3. CLI commands (docs/src/data/commands), sorted by path,
 *   4. the experiment and strict control status pages (generated by upstream),
 *   5. FAQ questions (docs/src/data/faq),
 *   6. patterns (docs/src/data/patterns).
 *
 * Published content depends on the latest Terragrunt release: upstream drops
 * every entry whose `since` is newer than the latest release tag when it builds
 * the site. Pass the same release with `--release` or `TERRAGRUNT_LATEST_RELEASE`
 * (default: `gh api repos/gruntwork-io/terragrunt/releases/latest`).
 *
 * Usage:
 *   TERRAGRUNT_REPO=<checkout> npm run update-docs-manifest
 *   npm run update-docs-manifest -- --repo <checkout> --release v1.2.1
 *
 * Options:
 *   --repo <path>      Terragrunt checkout (or TERRAGRUNT_REPO).
 *   --release <tag>    Latest release the site was built with (or TERRAGRUNT_LATEST_RELEASE).
 *   --keep-revision    Keep the UPSTREAM_REVISION already in the manifest instead
 *                      of writing the checkout's HEAD. Only for manifest-only
 *                      experiments and tests; a real re-pin must not use it.
 *
 * See docs/upstream-parity.md for the refresh procedure.
 */

import * as fs from 'fs';
import * as path from 'path';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';
import { parse as parseYaml } from 'yaml';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const MANIFEST_PATH = path.join(__dirname, '..', 'src', 'terragrunt', 'docs-manifest.ts');

/** One page of the manifest: the llms `# title`, its canonical URL path and its `>` description. */
export interface ManifestPage {
  title: string;
  path: string;
  description: string;
}

/** A source file from the checkout: `id` is its path relative to the collection root. */
export interface SourceFile {
  id: string;
  content: string;
}

/** The files of every upstream collection that contributes pages. */
export interface ManifestSources {
  docs: SourceFile[];
  hclBlocks: SourceFile[];
  hclAttributes: SourceFile[];
  hclFunctions: SourceFile[];
  commands: SourceFile[];
  faq: SourceFile[];
  patterns: SourceFile[];
}

type FrontmatterData = Record<string, unknown>;

const RELEASE_VERSION = /^v\d+\.\d+\.\d+$/;

// ---------------------------------------------------------------------------
// Pure functions
// ---------------------------------------------------------------------------

/**
 * Splits a Markdown/MDX source into its YAML frontmatter and body. A source
 * without frontmatter has empty data. Invalid YAML throws, because a guessed
 * title or description would put a wrong entry into the manifest.
 *
 * @param source - Full file content.
 * @returns The parsed frontmatter data and the text after the closing `---`.
 */
export function parseFrontmatter(source: string): { data: FrontmatterData; body: string } {
  const match = source.match(/^---[ \t]*\r?\n(?:([\s\S]*?)\r?\n)?---[ \t]*(?:\r?\n|$)/);
  if (!match) return { data: {}, body: source };
  const parsed: unknown = parseYaml(match[1] ?? '');
  if (parsed === null || parsed === undefined) return { data: {}, body: source.slice(match[0].length) };
  if (typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error('frontmatter must be a YAML mapping');
  }
  return { data: parsed as FrontmatterData, body: source.slice(match[0].length) };
}

/**
 * Returns true when `version` is at or below `latest`, both in `vX.Y.Z` form.
 * Compares numerically, so `v1.0.10` is newer than `v1.0.7`.
 */
export function isReleased(version: string, latest: string): boolean {
  const a = version.replace(/^v/, '').split('.').map(Number);
  const b = latest.replace(/^v/, '').split('.').map(Number);
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    const diff = (a[i] ?? 0) - (b[i] ?? 0);
    if (diff !== 0) return diff < 0;
  }
  return true;
}

/**
 * Mirrors upstream `isPublished`: content without `since` is always published,
 * otherwise it is published once the latest release reaches `since`.
 */
export function isPublished(since: unknown, latest: string): boolean {
  if (since === undefined || since === null) return true;
  if (typeof since !== 'string' || !RELEASE_VERSION.test(since)) {
    throw new Error(`since "${String(since)}" must have the form vX.Y.Z, e.g. v1.2.0`);
  }
  return isReleased(since, latest);
}

/**
 * Mirrors upstream `hasRenderableBody`: placeholder pages hold only HTML or
 * MDX comments, and upstream leaves them out of the llms output.
 */
export function hasRenderableBody(body: string | undefined): boolean {
  if (!body) return false;
  return (
    body
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/\{\/\*[\s\S]*?\*\/\}/g, '')
      .trim().length > 0
  );
}

function requireString(file: SourceFile, data: FrontmatterData, key: string): string {
  const value = data[key];
  if (typeof value !== 'string' || value.length === 0) {
    throw new Error(`${file.id}: frontmatter needs a "${key}" string`);
  }
  return value.trim();
}

/**
 * The description as the llms parser sees it: upstream writes `> <description>`
 * and the parser reads the first line, so a block scalar's trailing newline and
 * any further lines are not part of the manifest key.
 */
function llmsDescription(value: string): string {
  return value.trim().split(/\r?\n/)[0].trim();
}

function descriptionOf(file: SourceFile, data: FrontmatterData): string {
  const value = data.description;
  if (value === undefined || value === null) return '';
  if (typeof value !== 'string') throw new Error(`${file.id}: frontmatter "description" must be a string`);
  return llmsDescription(value);
}

function byText(a: string, b: string): number {
  return a.localeCompare(b, 'en');
}

/** Pages of the `docs` collection: not draft, published, with a body, sorted by slug. */
export function docsPages(files: SourceFile[], latest: string): ManifestPage[] {
  const pages: Array<ManifestPage & { slug: string }> = [];
  for (const file of files) {
    const { data, body } = parseFrontmatter(file.content);
    if (data.draft === true) continue;
    if (!isPublished(data.since, latest)) continue;
    if (!hasRenderableBody(body)) continue;
    const slug = requireString(file, data, 'slug');
    const hero = (data.hero ?? {}) as FrontmatterData;
    const heroTitle = typeof hero.title === 'string' ? hero.title : '';
    const heroTagline = typeof hero.tagline === 'string' ? llmsDescription(hero.tagline) : '';
    pages.push({
      slug,
      title: heroTitle || requireString(file, data, 'title'),
      path: `/${slug}/`,
      description: heroTagline || descriptionOf(file, data),
    });
  }
  pages.sort((a, b) => byText(a.slug, b.slug));
  return pages.map(({ title, path: pagePath, description }) => ({ title, path: pagePath, description }));
}

/** Pages of one HCL kind (`blocks`, `attributes`, `functions`), published only, sorted by name. */
export function hclPages(kind: string, files: SourceFile[], latest: string): ManifestPage[] {
  const pages: ManifestPage[] = [];
  for (const file of files) {
    const { data } = parseFrontmatter(file.content);
    if (!isPublished(data.since, latest)) continue;
    const name = requireString(file, data, 'name');
    pages.push({
      title: name,
      path: `/reference/hcl/${kind}/${name}/`,
      description: descriptionOf(file, data),
    });
  }
  return pages.sort((a, b) => byText(a.title, b.title));
}

/** Pages of the CLI commands collection, published only, sorted by command path. */
export function commandPages(files: SourceFile[], latest: string): ManifestPage[] {
  const pages: Array<ManifestPage & { commandPath: string }> = [];
  for (const file of files) {
    const { data } = parseFrontmatter(file.content);
    if (!isPublished(data.since, latest)) continue;
    const commandPath = requireString(file, data, 'path');
    pages.push({
      commandPath,
      title: requireString(file, data, 'name'),
      path: `/reference/cli/commands/${commandPath}/`,
      description: descriptionOf(file, data),
    });
  }
  pages.sort((a, b) => byText(a.commandPath, b.commandPath));
  return pages.map(({ title, path: pagePath, description }) => ({ title, path: pagePath, description }));
}

/**
 * The experiment and strict control status pages. Upstream builds these from
 * components, and their titles, descriptions and URLs are constants in
 * `EXPERIMENT_META` / `STRICT_CONTROL_META` (generated-pages.ts) and in the
 * `.astro` routes.
 */
export function statusPages(): ManifestPage[] {
  return [
    {
      title: 'Active Experiments',
      path: '/reference/experiments/active/',
      description: 'Experimental features available for opt-in.',
    },
    {
      title: 'Completed Experiments',
      path: '/reference/experiments/completed/',
      description: 'Experiments that have graduated to stable features.',
    },
    {
      title: 'Active Strict Controls',
      path: '/reference/strict-controls/active/',
      description: 'Strict controls that convert deprecated feature warnings into errors.',
    },
    {
      title: 'Completed Strict Controls',
      path: '/reference/strict-controls/completed/',
      description: 'Strict controls whose behaviour is now the default.',
    },
  ];
}

/**
 * Pages of the FAQ (`faq`, titled by `question`) or the patterns (`patterns`,
 * titled by `title`) collection. Sorted by the optional `order` ascending
 * (entries without one last), then by title. The URL id is the file path
 * without its extension.
 */
export function orderedEntryPages(
  collection: 'faq' | 'patterns',
  files: SourceFile[],
  urlPrefix: string,
): ManifestPage[] {
  const titleKey = collection === 'faq' ? 'question' : 'title';
  const entries = files.map(file => {
    const { data } = parseFrontmatter(file.content);
    const order = data.order;
    if (order !== undefined && typeof order !== 'number') {
      throw new Error(`${file.id}: frontmatter "order" must be a number`);
    }
    return {
      order: order ?? Number.POSITIVE_INFINITY,
      page: {
        title: requireString(file, data, titleKey),
        path: `${urlPrefix}${file.id.replace(/\.mdx?$/, '')}/`,
        description: descriptionOf(file, data),
      } satisfies ManifestPage,
    };
  });
  entries.sort((a, b) => (a.order !== b.order ? a.order - b.order : byText(a.page.title, b.page.title)));
  return entries.map(e => e.page);
}

/**
 * Combines all sources in the upstream llms order. Throws when two pages share
 * a URL or share both title and description, because the parser could not tell
 * them apart.
 */
export function deriveManifestPages(sources: ManifestSources, latest: string): ManifestPage[] {
  const pages = [
    ...docsPages(sources.docs, latest),
    ...hclPages('blocks', sources.hclBlocks, latest),
    ...hclPages('attributes', sources.hclAttributes, latest),
    ...hclPages('functions', sources.hclFunctions, latest),
    ...commandPages(sources.commands, latest),
    ...statusPages(),
    ...orderedEntryPages('faq', sources.faq, '/process/faq/'),
    ...orderedEntryPages('patterns', sources.patterns, '/guides/patterns/'),
  ];

  const urls = new Set<string>();
  const keys = new Map<string, string>();
  for (const page of pages) {
    if (urls.has(page.path)) throw new Error(`duplicate URL ${page.path}`);
    urls.add(page.path);
    const key = `${page.title}\n${page.description}`;
    const other = keys.get(key);
    if (other) {
      throw new Error(
        `${other} and ${page.path} have the same title and description (${JSON.stringify(page.title)}); the docs parser could not tell them apart`,
      );
    }
    keys.set(key, page.path);
  }
  return pages;
}

function quote(value: string): string {
  const escaped = value.replace(/\\/g, '\\\\').replace(/\n/g, '\\n').replace(/\r/g, '\\r');
  if (!escaped.includes("'")) return `'${escaped}'`;
  if (!escaped.includes('"')) return `"${escaped}"`;
  return `'${escaped.replace(/'/g, "\\'")}'`;
}

/**
 * Renders the content of src/terragrunt/docs-manifest.ts. An entry carries its
 * description only when its title occurs more than once, which is what the
 * parser needs to tell the pages apart.
 */
export function renderManifest(pages: ManifestPage[], meta: { revision: string; release: string }): string {
  const titleCounts = new Map<string, number>();
  for (const page of pages) titleCounts.set(page.title, (titleCounts.get(page.title) ?? 0) + 1);

  const rows = pages.map(page => {
    const parts = [quote(page.title), quote(page.path)];
    if ((titleCounts.get(page.title) ?? 0) > 1) parts.push(quote(page.description));
    return `  [${parts.join(', ')}],`;
  });

  return [
    '/**',
    ' * Canonical paths for the Terragrunt documentation inventory: one entry per page',
    ' * of the upstream llms-small.txt, in the order of its generator',
    ' * (`LLMS_PAGE_SOURCES` in docs/src/lib/generated-pages.ts): the docs collection',
    ' * by slug, the HCL blocks, attributes and functions by name, the CLI commands by',
    ' * path, the experiment and strict control status pages, the FAQ questions, the',
    ' * patterns.',
    ' *',
    ' * An entry is `[title, path]`. A title that occurs more than once has the page',
    ' * description as a third element, so the parser can tell the pages apart.',
    ' *',
    ` * Generated by \`npm run update-docs-manifest\` (scripts/update-docs-manifest.ts)`,
    ` * from an upstream checkout; do not edit by hand. Pages gated on a release are`,
    ` * included up to ${meta.release}.`,
    ' */',
    '/** The upstream Terragrunt revision this documentation inventory is pinned to. */',
    `export const UPSTREAM_REVISION = '${meta.revision}';`,
    '',
    'export const TERRAGRUNT_DOC_MANIFEST = [',
    ...rows,
    '] as const;',
    '',
  ].join('\n');
}

/** Reads `UPSTREAM_REVISION` from the source of an existing manifest. */
export function readUpstreamRevision(manifestSource: string): string {
  const match = manifestSource.match(/export const UPSTREAM_REVISION = '([0-9a-f]{40})'/);
  if (!match) throw new Error('could not find UPSTREAM_REVISION in the existing manifest');
  return match[1];
}

// ---------------------------------------------------------------------------
// File system and CLI
// ---------------------------------------------------------------------------

/** Reads the files with the given extensions below `root`; ignores names that start with `_`, like Astro. */
function readCollection(root: string, extensions: readonly string[]): SourceFile[] {
  if (!fs.existsSync(root)) throw new Error(`missing docs directory: ${root}`);
  const files: SourceFile[] = [];
  const walk = (dir: string): void => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (extensions.some(ext => entry.name.endsWith(ext))) {
        files.push({
          id: path.relative(root, full).split(path.sep).join('/'),
          content: fs.readFileSync(full, 'utf8'),
        });
      }
    }
  };
  walk(root);
  return files.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

/** Reads every collection that contributes pages from the docs tree of a checkout. */
export function readSources(repo: string): ManifestSources {
  const src = path.join(repo, 'docs', 'src');
  const both = ['.md', '.mdx'] as const;
  return {
    docs: readCollection(path.join(src, 'content', 'docs'), both),
    hclBlocks: readCollection(path.join(src, 'data', 'hcl', 'blocks'), ['.mdx']),
    hclAttributes: readCollection(path.join(src, 'data', 'hcl', 'attributes'), ['.mdx']),
    hclFunctions: readCollection(path.join(src, 'data', 'hcl', 'functions'), ['.mdx']),
    commands: readCollection(path.join(src, 'data', 'commands'), ['.mdx']),
    faq: readCollection(path.join(src, 'data', 'faq'), both),
    patterns: readCollection(path.join(src, 'data', 'patterns'), both),
  };
}

function option(name: string): string | undefined {
  const index = process.argv.indexOf(name);
  return index !== -1 ? process.argv[index + 1] : undefined;
}

function resolveRepo(): string {
  const repo = option('--repo') ?? process.env.TERRAGRUNT_REPO;
  if (!repo) {
    console.error('ERROR: set TERRAGRUNT_REPO or pass --repo <path> to a terragrunt checkout.');
    process.exit(1);
  }
  return repo;
}

function resolveRelease(): string {
  let release = option('--release') ?? process.env.TERRAGRUNT_LATEST_RELEASE;
  if (!release) {
    release = execFileSync(
      'gh',
      ['api', 'repos/gruntwork-io/terragrunt/releases/latest', '--jq', '.tag_name'],
      { encoding: 'utf8' },
    ).trim();
  }
  if (!RELEASE_VERSION.test(release)) {
    throw new Error(`latest release "${release}" must have the form vX.Y.Z; pass --release or set TERRAGRUNT_LATEST_RELEASE`);
  }
  return release;
}

function git(repo: string, ...args: string[]): string {
  return execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' }).trim();
}

function main(): void {
  const repo = resolveRepo();
  const release = resolveRelease();

  // A modified docs tree is not the pinned revision: the manifest would describe other pages.
  if (git(repo, 'status', '--porcelain', '--', 'docs')) {
    throw new Error(`${repo} has uncommitted changes under docs/; use a clean checkout of the revision to pin`);
  }
  const checkoutRevision = git(repo, 'rev-parse', 'HEAD');
  const revision = process.argv.includes('--keep-revision')
    ? readUpstreamRevision(fs.readFileSync(MANIFEST_PATH, 'utf8'))
    : checkoutRevision;

  const pages = deriveManifestPages(readSources(repo), release);

  const tmp = `${MANIFEST_PATH}.tmp-${process.pid}-${Date.now()}`;
  try {
    fs.writeFileSync(tmp, renderManifest(pages, { revision, release }), 'utf8');
    fs.renameSync(tmp, MANIFEST_PATH);
  } finally {
    // After a successful rename the temp file is gone; after a failed write or
    // rename it must not stay in src/terragrunt/.
    fs.rmSync(tmp, { force: true });
  }
  console.log(
    `Wrote ${pages.length} pages to ${path.relative(process.cwd(), MANIFEST_PATH)} ` +
      `(checkout ${checkoutRevision}, release ${release}, UPSTREAM_REVISION ${revision}).`,
  );
}

// Only run main when invoked directly, not when imported by tests.
if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  try {
    main();
  } catch (error) {
    console.error('Fatal error:', error);
    process.exit(1);
  }
}
